Map<int, int>? _mapping;

Map<int, int> _buildMapping() {
  final mapping = <int, int>{};
  for (var i = 0; i < _runs.length; i += 4) {
    final start = _runs[i], count = _runs[i + 1], step = _runs[i + 2];
    final delta = _runs[i + 3];
    for (var j = 0; j < count; j++) {
      mapping[start + j * step] = start + j * step + delta;
    }
  }
  return mapping;
}

/// Lower-cases [value] like JavaScript's `value.toLowerCase()`.
String jsToLowerCase(String value) {
  var i = 0;
  final length = value.length;
  // ASCII fast path: nothing to do until an upper-case or non-ASCII unit.
  while (i < length) {
    final unit = value.codeUnitAt(i);
    if (unit >= 0x80 || (unit >= 0x41 && unit <= 0x5A)) break;
    i++;
  }
  if (i == length) return value;
  final mapping = _mapping ??= _buildMapping();
  final buffer = StringBuffer(value.substring(0, i));
  while (i < length) {
    var codePoint = value.codeUnitAt(i);
    var width = 1;
    if (codePoint >= 0xD800 && codePoint <= 0xDBFF && i + 1 < length) {
      final low = value.codeUnitAt(i + 1);
      if (low >= 0xDC00 && low <= 0xDFFF) {
        codePoint = 0x10000 + ((codePoint - 0xD800) << 10) + (low - 0xDC00);
        width = 2;
      }
    }
    if (codePoint >= 0x41 && codePoint <= 0x5A) {
      buffer.writeCharCode(codePoint + 32);
    } else if (codePoint < 0x80) {
      buffer.writeCharCode(codePoint);
    } else if (codePoint == 0x130) {
      buffer.write('i\u0307');
    } else {
      buffer.writeCharCode(mapping[codePoint] ?? codePoint);
    }
    i += width;
  }
  return buffer.toString();
}
